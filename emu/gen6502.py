#!/usr/bin/env python3
"""Generate emu/core.asm: a 6502 interpreter for the Z80/R800.

Registers: 6502 PC = DE; A/X/Y/S/P and the instruction counter live in RAM
(RV_*).  6502 memory is 4 mapper segments (SEG0..SEG0+3) seen through Z80
page 2 ($8000-$BFFF).  Decimal mode is NOT emulated (Last Ninja never sets D).
Every handler ends with `jp next`.  Hot paths are not optimised yet.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'msx', 'tools'))
from parse6502 import OPS  # noqa: E402

out = []
n = [0]


def e(*lines):
    out.extend(lines)


def lab():
    n[0] += 1
    return 'L%d' % n[0]


PRELUDE = r"""
; ---- generated by gen6502.py: do not edit ----
; RV_* variables, SEG0 and PORT_P2 come from the including file.

rd:                     ; HL=6502 addr -> A ; keeps HL,BC,DE
	if TRAPS
	ld a,h
	cp $D0
	jr c,rd_ram
	cp $E0
	jr nc,rd_ram
	ld a,(RV_IO)
	or a
	jp nz,io_rd
rd_ram:
	endif
	push hl
	ld a,h
	rlca
	rlca
	and 3
	add a,SEG0
	out (PORT_P2),a
	ld a,h
	and $3F
	or $80
	ld h,a
	ld a,(hl)
	pop hl
	ret

wr:                     ; HL=6502 addr, A=value ; keeps HL,BC,DE
	if TRAPS
	push af
	ld a,h
	or a
	jr z,wr_zp
	cp $D0
	jr c,wr_ram0
	cp $E0
	jr nc,wr_ram0
	ld a,(RV_IO)
	or a
	jp nz,io_wr
	jr wr_ram0
wr_zp:
	ld a,l
	dec a
	jr nz,wr_ram0
	pop af
	call port_wr
	push af
wr_ram0:
	pop af
	endif
	push hl
	push af
	ld a,h
	rlca
	rlca
	and 3
	add a,SEG0
	out (PORT_P2),a
	ld a,h
	and $3F
	or $80
	ld h,a
	pop af
	ld (hl),a
	pop hl
	ret

fetch8:
	ld h,d
	ld l,e
	call rd
	inc de
	ret

fetch16:                ; -> HL (clobbers BC)
	call fetch8
	ld c,a
	call fetch8
	ld h,a
	ld l,c
	ret

ea_zp:
	call fetch8
	ld l,a
	ld h,0
	ret
ea_zpx:
	call fetch8
	ld hl,RV_X
	add a,(hl)
	ld l,a
	ld h,0
	ret
ea_zpy:
	call fetch8
	ld hl,RV_Y
	add a,(hl)
	ld l,a
	ld h,0
	ret
ea_abx:
	call fetch16
	ld a,(RV_X)
	ld c,a
	ld b,0
	add hl,bc
	ret
ea_aby:
	call fetch16
	ld a,(RV_Y)
	ld c,a
	ld b,0
	add hl,bc
	ret
rdzp16:                 ; HL=zp addr -> HL = word (zp wrap)
	push de
	call rd
	ld b,a
	ld a,l
	inc a
	ld l,a
	ld h,0
	call rd
	ld h,a
	ld l,b
	pop de
	ret
ea_izx:
	call fetch8
	ld hl,RV_X
	add a,(hl)
	ld l,a
	ld h,0
	jp rdzp16
ea_izy:
	call fetch8
	ld l,a
	ld h,0
	call rdzp16
	ld a,(RV_Y)
	ld c,a
	ld b,0
	add hl,bc
	ret
ea_ind:                 ; JMP (ind) with the page-wrap bug
	call fetch16
	call rd
	ld b,a
	inc l
	call rd
	ld h,a
	ld l,b
	ret

; ---- flag packers: C = Z80 F on entry -----------------------------------
fl_nz:                  ; A = result
	or a
	push af
	pop bc
	ld hl,RV_P
	ld a,(hl)
	and $7D
	ld b,a
	ld a,c
	and $80
	or b
	ld b,a
	ld a,c
	and $40
	rrca
	rrca
	rrca
	rrca
	rrca
	or b
	ld (hl),a
	ret
fl_nzc_c:               ; C=F, Z80 carry == 6502 carry
	ld hl,RV_P
	ld a,(hl)
	and $7C
	ld b,a
	ld a,c
	and $80
	or b
	ld b,a
	ld a,c
	and $40
	rrca
	rrca
	rrca
	rrca
	rrca
	or b
	ld b,a
	ld a,c
	and 1
	or b
	ld (hl),a
	ret
fl_nzc:                 ; flags live in F
	push af
	pop bc
	jr fl_nzc_c
fl_cmp:                 ; flags live in F, 6502 C = not Z80 C
	push af
	pop bc
	ld a,c
	xor 1
	ld c,a
	jr fl_nzc_c
fl_adc:                 ; flags live in F
	push af
	pop bc
fl_adc_c:
	ld hl,RV_P
	ld a,(hl)
	and $3C
	ld b,a
	ld a,c
	and $80
	or b
	ld b,a
	ld a,c
	and $40
	rrca
	rrca
	rrca
	rrca
	rrca
	or b
	ld b,a
	ld a,c
	and 1
	or b
	ld b,a
	ld a,c
	and 4
	rlca
	rlca
	rlca
	rlca
	or b
	ld (hl),a
	ret
fl_sbc:
	push af
	pop bc
	ld a,c
	xor 1
	ld c,a
	jr fl_adc_c

push8:                  ; A = value
	ld b,a
	ld hl,RV_S
	ld a,(hl)
	dec (hl)
	ld l,a
	ld h,1
	ld a,b
	jp wr
pop8:                   ; -> A
	ld hl,RV_S
	inc (hl)
	ld a,(hl)
	ld l,a
	ld h,1
	jp rd

next:
	ld hl,(RV_CNT)
	ld a,h
	or l
	jp z,emu_done
	dec hl
	ld (RV_CNT),hl
	call fetch8
	ld l,a
	ld h,0
	add hl,hl
	ld bc,optab
	add hl,bc
	ld a,(hl)
	inc hl
	ld h,(hl)
	ld l,a
	jp (hl)

emu_bad:
	jp emu_bad
"""

EA = {'zp': 'ea_zp', 'zpx': 'ea_zpx', 'zpy': 'ea_zpy', 'abs': 'fetch16', 'abx': 'ea_abx',
      'aby': 'ea_aby', 'izx': 'ea_izx', 'izy': 'ea_izy'}
BR = {'bpl': (0x80, 0), 'bmi': (0x80, 1), 'bvc': (0x40, 0), 'bvs': (0x40, 1),
      'bcc': (1, 0), 'bcs': (1, 1), 'bne': (2, 0), 'beq': (2, 1)}
SHIFT = {'asl': 'sla a', 'lsr': 'srl a', 'rol': 'rl a', 'ror': 'rr a'}
REGV = {'lda': 'RV_A', 'ldx': 'RV_X', 'ldy': 'RV_Y'}


def load_val(mode):
    """Emit code leaving the operand value in A."""
    if mode == 'imm':
        e('\tcall fetch8')
    else:
        e('\tcall %s' % EA[mode], '\tcall rd')


def pre_carry_in():
    e('\tld a,(RV_P)', '\trra')


def handler(op, mn, mode):
    name = 'h_%02X' % op
    e('%s:' % name)
    if mn in REGV:
        load_val(mode)
        e('\tld (%s),a' % REGV[mn], '\tcall fl_nz', '\tjp next')
    elif mn in ('sta', 'stx', 'sty'):
        e('\tcall %s' % EA[mode], '\tld a,(%s)' % {'sta': 'RV_A', 'stx': 'RV_X', 'sty': 'RV_Y'}[mn],
          '\tcall wr', '\tjp next')
    elif mn in ('and', 'ora', 'eor'):
        load_val(mode)
        e('\tld hl,RV_A', '\t%s (hl)' % {'and': 'and', 'ora': 'or', 'eor': 'xor'}[mn],
          '\tld (hl),a', '\tcall fl_nz', '\tjp next')
    elif mn == 'adc':
        load_val(mode)
        e('\tld b,a')
        pre_carry_in()
        e('\tld a,(RV_A)', '\tadc a,b', '\tld (RV_A),a', '\tcall fl_adc', '\tjp next')
    elif mn == 'sbc':
        load_val(mode)
        e('\tld b,a', '\tld a,(RV_P)', '\tcpl', '\trra', '\tld a,(RV_A)', '\tsbc a,b',
          '\tld (RV_A),a', '\tcall fl_sbc', '\tjp next')
    elif mn in ('cmp', 'cpx', 'cpy'):
        load_val(mode)
        e('\tld b,a', '\tld a,(%s)' % {'cmp': 'RV_A', 'cpx': 'RV_X', 'cpy': 'RV_Y'}[mn],
          '\tcp b', '\tcall fl_cmp', '\tjp next')
    elif mn == 'bit':
        load_val(mode)
        l = lab()
        e('\tld b,a', '\tld hl,RV_P', '\tld a,(hl)', '\tand $3D', '\tld c,a', '\tld a,b',
          '\tand $C0', '\tor c', '\tld c,a', '\tld a,(RV_A)', '\tand b', '\tjr nz,%s' % l,
          '\tset 1,c', '%s:' % l, '\tld (hl),c', '\tjp next')
    elif mn in SHIFT or mn in ('inc', 'dec'):
        def body():
            if mn in SHIFT:
                if mn in ('rol', 'ror'):
                    e('\tld b,a', '\tld a,(RV_P)', '\trra', '\tld a,b')
                e('\t' + SHIFT[mn], '\tld (RV_T),a', '\tcall fl_nzc')
            else:
                e('\t%s a' % mn, '\tld (RV_T),a', '\tcall fl_nz')
        if mode == 'acc':
            e('\tld a,(RV_A)')
            body()
            e('\tld a,(RV_T)', '\tld (RV_A),a', '\tjp next')
        else:
            e('\tcall %s' % EA[mode], '\tpush hl', '\tcall rd')
            body()
            e('\tpop hl', '\tld a,(RV_T)', '\tcall wr', '\tjp next')
    elif mn in ('tax', 'tay', 'txa', 'tya', 'tsx'):
        s, d = {'tax': ('A', 'X'), 'tay': ('A', 'Y'), 'txa': ('X', 'A'), 'tya': ('Y', 'A'),
                'tsx': ('S', 'X')}[mn]
        e('\tld a,(RV_%s)' % s, '\tld (RV_%s),a' % d, '\tcall fl_nz', '\tjp next')
    elif mn == 'txs':
        e('\tld a,(RV_X)', '\tld (RV_S),a', '\tjp next')
    elif mn in ('inx', 'iny', 'dex', 'dey'):
        e('\tld hl,RV_%s' % mn[2].upper(), '\t%s (hl)' % ('inc' if mn[0] == 'i' else 'dec'),
          '\tld a,(hl)', '\tcall fl_nz', '\tjp next')
    elif mn in ('clc', 'sec', 'cli', 'sei', 'cld', 'sed', 'clv'):
        bit = {'c': 0, 'i': 2, 'd': 3, 'v': 6}[mn[2]]
        e('\tld hl,RV_P', '\t%s %d,(hl)' % ('set' if mn[1] == 'e' else 'res', bit), '\tjp next')
    elif mn in BR:
        mask, want = BR[mn]
        take = lab()
        e('\tcall fetch8', '\tld c,a', '\tld a,(RV_P)', '\tand %d' % mask,
          '\tjr %s,%s' % ('nz' if want else 'z', take), '\tjp next', '%s:' % take,
          '\tld l,c', '\tld a,c', '\tadd a,a', '\tsbc a,a', '\tld h,a', '\tadd hl,de',
          '\tex de,hl', '\tjp next')
    elif mn == 'pha':
        e('\tld a,(RV_A)', '\tcall push8', '\tjp next')
    elif mn == 'php':
        e('\tld a,(RV_P)', '\tor $30', '\tcall push8', '\tjp next')
    elif mn == 'pla':
        e('\tcall pop8', '\tld (RV_A),a', '\tcall fl_nz', '\tjp next')
    elif mn == 'plp':
        e('\tcall pop8', '\tor $20', '\tld (RV_P),a', '\tjp next')
    elif mn == 'jmp':
        if mode == 'abs':
            e('\tcall fetch16')
        else:
            e('\tcall ea_ind')
        e('\tex de,hl', '\tjp next')
    elif mn == 'jsr':
        e('\tcall fetch16', '\tpush hl', '\tdec de', '\tld a,d', '\tcall push8', '\tld a,e',
          '\tcall push8', '\tpop de', '\tjp next')
    elif mn == 'rts':
        e('\tcall pop8', '\tld e,a', '\tcall pop8', '\tld d,a', '\tinc de', '\tjp next')
    elif mn == 'rti':
        e('\tcall pop8', '\tor $20', '\tld (RV_P),a', '\tcall pop8', '\tld e,a',
          '\tcall pop8', '\tld d,a', '\tjp next')
    elif mn == 'brk':
        e('\tinc de', '\tld a,d', '\tcall push8', '\tld a,e', '\tcall push8',
          '\tld a,(RV_P)', '\tor $30', '\tcall push8', '\tld hl,RV_P', '\tset 2,(hl)',
          '\tld hl,$FFFE', '\tcall rd', '\tld c,a', '\tld hl,$FFFF', '\tcall rd',
          '\tld d,a', '\tld e,c', '\tjp next')
    elif mn == 'nop':
        e('\tjp next')
    else:
        raise ValueError(mn)
    return name


def main():
    out.append(PRELUDE)
    names = {}
    for op in sorted(OPS):
        mn, mode, _ = OPS[op]
        names[op] = handler(op, mn, mode)
    e('optab:')
    for op in range(256):
        e('\tdw %s' % names.get(op, 'emu_bad'))
    open(os.path.join(os.path.dirname(__file__), 'core.asm'), 'w').write('\n'.join(out) + '\n')
    print('core.asm: %d handlers' % len(names))


if __name__ == '__main__':
    main()
